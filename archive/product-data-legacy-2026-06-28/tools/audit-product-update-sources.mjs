import fs from "node:fs";

const strict = process.argv.includes("--strict");

const files = {
  wyrestormCatalogue: "data-imports/wyrestorm-catalogue-current.csv",
  wyrestormLifecycle: "data-imports/wyrestorm-lifecycle-current.csv",
  competitorFingerprints: "data-imports/competitor-fingerprints-current.csv",
  competitorReviewNotes: "data-imports/competitor-review-notes.csv"
};

function fail(message) {
  console.error(`[product-update-source-audit] ${message}`);
  process.exit(1);
}

function read(file) {
  if (!fs.existsSync(file)) {
    fail(`Missing required source file: ${file}`);
  }

  return fs.readFileSync(file, "utf8");
}

function rows(csvText) {
  return csvText
    .split(/\r?\n/g)
    .map((line) => line.trim())
    .filter(Boolean)
    .slice(1);
}

function contains(text, value) {
  return text.toLowerCase().includes(value.toLowerCase());
}

const wyrestormCatalogue = read(files.wyrestormCatalogue);
const wyrestormLifecycle = read(files.wyrestormLifecycle);
const competitorFingerprints = read(files.competitorFingerprints);
const competitorReviewNotes = read(files.competitorReviewNotes);

const wyrestormRows = rows(wyrestormCatalogue);
const lifecycleRows = rows(wyrestormLifecycle);
const competitorRows = rows(competitorFingerprints);
const competitorReviewRows = rows(competitorReviewNotes);

const sampleSignals = [
  contains(wyrestormCatalogue, "NHD-500-TX") && wyrestormRows.length === 1,
  contains(competitorFingerprints, "Blustream") && contains(competitorFingerprints, "IP250UHD-TX") && competitorRows.length === 1,
  contains(wyrestormCatalogue, "Official WyreStorm catalogue or datasheet"),
  contains(competitorFingerprints, "Reviewed competitor profile")
];

const sampleOnly = sampleSignals.some(Boolean);

const warnings = [];

if (sampleOnly) {
  warnings.push("Import files still appear to contain scaffold sample rows.");
}

if (wyrestormRows.length < 25) {
  warnings.push(`WyreStorm catalogue source is very small: ${wyrestormRows.length} data row(s).`);
}

if (lifecycleRows.length < 25) {
  warnings.push(`WyreStorm lifecycle source is very small: ${lifecycleRows.length} data row(s).`);
}

if (competitorRows.length < 10) {
  warnings.push(`Competitor fingerprint source is very small: ${competitorRows.length} data row(s).`);
}

if (competitorReviewRows.length < 1) {
  warnings.push("Competitor review notes source is empty.");
}

const report = [
  "# Product update source readiness",
  "",
  "Generated by the product-update source audit. Timestamps are intentionally omitted to avoid no-op diffs.",
  "",
  "## Source counts",
  "",
  `- WyreStorm catalogue rows: ${wyrestormRows.length}`,
  `- WyreStorm lifecycle rows: ${lifecycleRows.length}`,
  `- Competitor fingerprint rows: ${competitorRows.length}`,
  `- Competitor review-note rows: ${competitorReviewRows.length}`,
  "",
  "## Readiness",
  "",
  `- Sample-only source data detected: ${sampleOnly ? "yes" : "no"}`,
  `- Strict mode: ${strict ? "yes" : "no"}`,
  "",
  "## Warnings",
  "",
  ...(warnings.length ? warnings.map((warning) => `- ${warning}`) : ["- None"]),
  "",
  "## Policy",
  "",
  "- WyreStorm CSVs should come from a reviewed catalogue or lifecycle export.",
  "- Competitor CSVs should contain reviewed comparison fingerprints only.",
  "- Competitor rows are comparison-only and must not enter WyreStorm BOMs.",
  "- Strict mode should be used before treating imported data as production-ready."
].join("\n");

fs.mkdirSync("docs", { recursive: true });
fs.writeFileSync("docs/product-update-source-readiness.md", `${report}\n`, "utf8");

console.log("[product-update-source-audit] Source readiness report written to docs/product-update-source-readiness.md");

if (warnings.length > 0) {
  console.log("[product-update-source-audit] Warnings:");
  for (const warning of warnings) {
    console.log(`- ${warning}`);
  }
}

if (strict && warnings.length > 0) {
  fail("Strict source-readiness check failed. Replace scaffold sample data with reviewed source exports.");
}

console.log("[product-update-source-audit] Source-readiness audit complete.");
