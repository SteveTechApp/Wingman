# 3) CompetitorMatchService.ts (catalog-backed scoring)
# -------------------------------------------------------------------
$svc = "src\competitor\CompetitorMatchService.ts"
Backup-File $svc
Write-Utf8NoBom $svc @(
'import competitorsRaw from "./competitors.json";',
'import type { CompetitorItem, MatchResult } from "./types";',
'import { listAll, isSelectable } from "@/catalog/CatalogService";',
'import type { Product } from "@/catalog/types";',
'',
'const COMPETITORS: CompetitorItem[] = competitorsRaw as any;',
'',
'function norm(s: string){ return (s || "").toLowerCase().trim(); }',
'',
'function scoreResolution(a?: string, b?: string){',
'  const order: Record<string, number> = { "1080p60": 1, "4K30": 2, "4K60": 3, "4K120": 4 };',
'  if(!a || !b) return { score: 0, reason: "No resolution data" };',
'  const sa = order[a] || 0;',
'  const sb = order[b] || 0;',
'  if(sa === 0 || sb === 0) return { score: 0, reason: "Unknown resolution enum" };',
'  if(sb >= sa) return { score: 10, reason: `Meets/exceeds ${a}` };',
'  return { score: -15, reason: `Below ${a}` };',
'}',
'',
'function overlapTags(a?: string[], b?: string[]){',
'  const A = new Set((a || []).map(norm));',
'  const B = new Set((b || []).map(norm));',
'  let hit = 0;',
'  for(const t of A){ if(B.has(t)) hit++; }',
'  return hit;',
'}',
'',
'function baseCategoryScore(cCat: string, p: Product){',
'  if(p.category === cCat) return { score: 35, reason: "Category match" };',
'  // light mapping',
'  if(cCat === "Switcher" && p.category === "Matrix") return { score: 18, reason: "Switcher→Matrix adjacent" };',
'  if(cCat === "Matrix" && p.category === "Switcher") return { score: 18, reason: "Matrix→Switcher adjacent" };',
'  return { score: -10, reason: "Category mismatch" };',
'}',
'',
'function roleScore(cRole: string, p: Product){',
'  if(p.role === cRole) return { score: 20, reason: "Role match" };',
'  // TRX is flexible',
'  if(cRole === "TX" && p.role === "TRX") return { score: 14, reason: "TRX can act as TX" };',
'  if(cRole === "RX" && p.role === "TRX") return { score: 14, reason: "TRX can act as RX" };',
'  return { score: -8, reason: "Role mismatch" };',
'}',
'',
'function lifecyclePenalty(p: Product){',
'  if(p.lifecycle === "eol") return { score: -100, reason: "EoL blocked" };',
'  if(p.lifecycle === "legacy") return { score: -8, reason: "Legacy penalty" };',
'  return { score: 0, reason: "Current lifecycle" };',
'}',
'',
'export function listCompetitors(): CompetitorItem[] {',
'  return [...COMPETITORS].sort((a,b) => (a.brand+a.model).localeCompare(b.brand+b.model));',
'}',
'',
'export function searchCompetitors(q: string): CompetitorItem[] {',
'  const s = norm(q);',
'  if(!s) return listCompetitors();',
'  return COMPETITORS.filter(c => {',
'    const hay = norm([c.brand, c.model, c.name, c.category, c.role, ...(c.tags||[]), ...(c.notes||[])].join(" "));',
'    return hay.includes(s);',
'  });',
'}',
'',
'export function matchToCatalog(competitor: CompetitorItem, topN = 5): MatchResult[] {',
'  const catalog = listAll();',
'  const scored = catalog.map(p => {',
'    let score = 0;',
'    const reasons: string[] = [];',
'',
'    const cat = baseCategoryScore(competitor.category, p);',
'    score += cat.score; reasons.push(cat.reason);',
'',
'    const rol = roleScore(competitor.role, p);',
'    score += rol.score; reasons.push(rol.reason);',
'',
'    const res = scoreResolution(competitor.video?.maxResolution, p.video?.maxResolution);',
'    score += res.score; if(res.score !== 0) reasons.push(res.reason);',
'',
'    const tagHits = overlapTags(competitor.tags, p.tags);',
'    if(tagHits > 0){ score += Math.min(12, tagHits * 4); reasons.push(`Tag overlap x${tagHits}`); }',
'',
'    const life = lifecyclePenalty(p);',
'    score += life.score; reasons.push(life.reason);',
'',
'    // Clamp + convert to confidence',
'    const clamped = Math.max(-100, Math.min(100, score));',
'    const confidence = Math.max(0, Math.min(100, Math.round((clamped + 10) * 0.9)));',
'',
'    return { p, confidence, reasons };',
'  })',
'  .filter(x => x.confidence > 0)',
'  .sort((a,b) => b.confidence - a.confidence)',
'  .slice(0, topN);',
'',
'  return scored.map(x => ({',
'    competitor,',
'    sku: x.p.sku,',
'    name: x.p.name,',
'    confidence: x.confidence,',
'    reasons: x.reasons.filter(Boolean),',
'  }));',
'}',
'',
'export function canAddSku(sku: string): boolean {',
'  const p = listAll().find(x => x.sku === sku);',
'  if(!p) return false;',
'  return isSelectable(p);',
'}'
)

