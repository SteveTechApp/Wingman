function Write-Utf8NoBom([string]$path, [string[]]$lines){
  $dir = Split-Path $path -Parent
  Ensure-Dir $dir
  $enc = New-Object System.Text.UTF8Encoding($false)
  $content = ($lines -join "`r`n") + "`r`n"
  [System.IO.File]::WriteAllText($path, $content, $enc)
}

